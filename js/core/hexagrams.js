// 卦名 -> 上下卦反向索引
const NAME_TO_TRIGRAMS = {};
for (const [key, name] of Object.entries(HEXAGRAM_MAP)) {
    const [upper, lower] = key.split('_').map(Number);
    NAME_TO_TRIGRAMS[name] = { upper, lower };
}

/** 通过上下卦获取卦名 */
export function getHexagramName(upperId, lowerId) {
    return HEXAGRAM_MAP[`${upperId}_${lowerId}`] || null;
}

/** 通过卦名获取上下卦 */
export function getHexagramTrigrams(name) {
    return NAME_TO_TRIGRAMS[name] || null;
}

/** 获取所有卦名列表 */
export function getAllHexagramNames() {
    return Object.values(HEXAGRAM_MAP);
}

